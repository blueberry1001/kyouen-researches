def residual_graph(board: Board, occ: int):
    moves = board.legal_moves(occ)
    adj = {v: [] for v in moves}
    for i in range(len(moves)):
        for j in range(i + 1, len(moves)):
            p, q = moves[i], moves[j]
            for quad in board.quads_by_pt[p]:
                if (quad >> q) & 1:
                    rest = quad & ~(1 << p) & ~(1 << q)
                    if rest.bit_count() == 2 and (rest & ~occ) == 0:
                        adj[p].append(q)
                        adj[q].append(p)
                        break
    return adj


def comps(adj):
    seen = set()
    out = []
    for v in adj:
        if v in seen:
            continue
        stack = [v]
        seen.add(v)
        c = []
        while stack:
            u = stack.pop()
            c.append(u)
            for w in adj[u]:
                if w not in seen:
                    seen.add(w)
                    stack.append(w)
        out.append(c)
    return out


def is_tree(comp, adj):
    n = len(comp)
    e = sum(1 for v in comp for w in adj[v] if w in comp) // 2
    return e == n - 1


def degseq(comp, adj):
    return tuple(sorted(sum(1 for w in adj[v] if w in comp) for v in comp))


# all trees on 1..6 vertices as sorted degree sequences (unlabeled trees)
# generated by Prüfer-like enumeration below
def all_tree_degseqs(max_n: int = 6) -> dict[int, set]:
    """All sorted degree sequences of trees on k vertices, k=1..max_n."""
    from itertools import product

    result = {k: set() for k in range(1, max_n + 1)}
    result[1].add((0,))
    for k in range(2, max_n + 1):
        # Prüfer sequences of length k-2 over {0..k-1}
        for prufer in product(range(k), repeat=k - 2):
            deg = [1] * k
            for x in prufer:
                deg[x] += 1
            # build tree to verify (deg is enough)
            if sum(deg) != 2 * (k - 1):
                continue
            result[k].add(tuple(sorted(deg)))
    return result


def main() -> None:
    n = 5
    board = board_square(n)
    print(f"n={n} V={board.V} quads={len(board.quads)}", flush=True)

    if os.path.exists(GPATH):
        raw = json.load(open(GPATH))
        grundy = {int(k): v for k, v in raw.items()}
        print(f"loaded grundy {len(grundy)}", flush=True)
    else:
        grundy = board.solve_grundy()
        # keys are ints; json needs str
        json.dump({str(k): v for k, v in grundy.items()}, open(GPATH, "w"))
        print(f"computed grundy {len(grundy)}", flush=True)

    safe_sets = sorted(grundy.keys())
    legal = {}
    for occ in safe_sets:
        legal[occ] = board.legal_moves(occ)

    def children(occ):
        return [occ | (1 << v) for v in legal[occ]]

    # B231
    g_hist = Counter(grundy.values())
    max_g = max(g_hist)
    b231 = {
        "max_g": max_g,
        "achieved": sorted(g_hist),
        "hist": {str(k): g_hist[k] for k in sorted(g_hist)},
        "continuous": sorted(g_hist) == list(range(max_g + 1)),
        "max_g_ge_n": max_g >= n,
    }
    print("b231", b231, flush=True)

    # depth / proof DP
    by_size = sorted(safe_sets, key=lambda s: -s.bit_count())
    depth_m = {}
    proof_m = {}
    for occ in by_size:
        ch = children(occ)
        if not ch:
            depth_m[occ] = 0
            proof_m[occ] = 1
            continue
        if grundy[occ] == 0:
            depth_m[occ] = 1 + max(depth_m[c] for c in ch)
            proof_m[occ] = 1 + sum(proof_m[c] for c in ch)
        else:
            win = [c for c in ch if grundy[c] == 0]
            depth_m[occ] = 1 + min(depth_m[c] for c in win)
            proof_m[occ] = 1 + min(proof_m[c] for c in win)

    # B247
    disjoint = []
    for occ in safe_sets:
        if grundy[occ] == 0:
            continue
        win = [c for c in children(occ) if grundy[c] == 0]
        if len(win) < 2:
            continue
        bd = min(depth_m[c] for c in win)
        bp = min(proof_m[c] for c in win)
        sd = {c for c in win if depth_m[c] == bd}
        sp = {c for c in win if proof_m[c] == bp}
        if sd.isdisjoint(sp):
            def mov(child):
                return (child ^ occ).bit_length() - 1
            disjoint.append({
                "occ": occ, "stones": occ.bit_count(),
                "n_win": len(win), "depth_min": bd, "proof_min": bp,
                "depth_moves": [mov(c) for c in sd],
                "proof_moves": [mov(c) for c in sp],
            })
    b247 = {"count": len(disjoint), "witnesses": disjoint[:5]}
    print("b247", b247["count"], flush=True)

    # B249 g=1
    by_depth = defaultdict(list)
    for occ in safe_sets:
        if grundy[occ] == 1:
            by_depth[depth_m[occ]].append(proof_m[occ])
    b249 = {
        "n_g1": sum(1 for g in grundy.values() if g == 1),
        "max_proof_by_depth": {str(d): max(by_depth[d]) for d in sorted(by_depth)},
        "count_by_depth": {str(d): len(by_depth[d]) for d in sorted(by_depth)},
    }
    print("b249", b249, flush=True)

    # B241: winning first moves and their winning replies
    # W = {p : g({p}) == 0}  (first move p leaves opponent at P)
    W = [p for p in range(board.V) if grundy[1 << p] == 0]
    # D4 orbits of W
    def d4(p):
        x, y = p % n, p // n
        out = set()
        for (a, b) in [(x, y), (y, x), (x, n - 1 - y), (n - 1 - y, x),
                       (n - 1 - x, y), (y, n - 1 - x), (n - 1 - x, n - 1 - y),
                       (n - 1 - y, n - 1 - x)]:
            out.add(b * n + a)
        return out

    unseen = set(W)
    orbits = []
    while unseen:
        p = min(unseen)
        orb = d4(p) & set(W)
        orbits.append(sorted(orb))
        unseen -= orb
    # winning replies from each W point (opponent at P after first? wait)
    # If p in W, then g({p})=0 means opponent to move at {p} is at P, so p is
    # winning FIRST move. The "response" of the winner is already p.
    # B241: "勝ち初手9点を個別の探索木に分けず、初手の軌道をパラメータに持つ共通の短いルール"
    # So we need: for each winning first move p, a reply strategy. The second
    # player is at P after p... wait first player plays p, then second player
    # faces g({p})=0 so second player loses with perfect play. The "応答法"
    # is the FIRST player's continued strategy after second player's reply.
    # Measure: from {p}, for each opponent reply q, the unique/short list of
    # winning continuations for first player.
    reply_profile = {}
    for p in W:
        s = 1 << p
        opp_replies = children(s)
        # for each opp reply, winning moves of first player
        prof = []
        for oq in opp_replies:
            winmv = [v for v in legal[oq] if grundy[oq | (1 << v)] == 0]
            prof.append(len(winmv))
        reply_profile[p] = {
            "n_opp_replies": len(opp_replies),
            "win_counts": sorted(prof),
            "all_have_unique_win": all(x == 1 for x in prof),
            "min_win": min(prof) if prof else 0,
            "max_win": max(prof) if prof else 0,
        }
    # how uniform is the profile across W?
    sigs = Counter()
    for p in W:
        sigs[tuple(reply_profile[p]["win_counts"])] += 1
    b241 = {
        "W": W,
        "n_W": len(W),
        "d4_orbits": orbits,
        "n_d4_orbits": len(orbits),
        "all_unique_win_continuation": all(reply_profile[p]["all_have_unique_win"] for p in W),
        "profile_sig_counts": {str(k): v for k, v in sigs.items()},
        "n_distinct_profiles": len(sigs),
    }
    print("b241", b241["n_W"], "orbits", b241["n_d4_orbits"], "profiles", b241["n_distinct_profiles"], flush=True)

    # B233/B232: residual tree shapes on a SUBSET (too heavy for all 151k).
    # Sample: all states with |S|<=4, and all maximal-adjacent states.
    tree_shapes = set()
    max_comp = 0
    checked = 0
    for occ in safe_sets:
        if occ.bit_count() > 5:
            continue
        adj = residual_graph(board, occ)
        checked += 1
        for c in comps(adj):
            max_comp = max(max_comp, len(c))
            if is_tree(c, adj):
                tree_shapes.add(degseq(c, adj))
    tseqs = all_tree_degseqs(6)
    b233 = {
        "checked_states_Sle5": checked,
        "tree_shapes_found": sorted(tree_shapes),
        "n_tree_shapes": len(tree_shapes),
        "all_trees_upto4_as_degseq": all(tseqs[k] <= tree_shapes for k in (1, 2, 3, 4)),
        "trees_upto4_expected": {str(k): sorted(tseqs[k]) for k in (1, 2, 3, 4)},
        "trees_upto5_expected": {str(k): sorted(tseqs[k]) for k in (5,)},
        "trees5_found": sorted(tseqs[5] & tree_shapes),
        "trees5_missing": sorted(tseqs[5] - tree_shapes),
        "trees6_missing": sorted(tseqs[6] - tree_shapes),
        "max_comp_size_in_sample": max_comp,
    }
    print("b233 trees5 missing", b233["trees5_missing"], flush=True)

    # B236 unique-win robust depth on n=5, only from empty and a sample of N
    sys.setrecursionlimit(30000)
    from functools import lru_cache

    @lru_cache(maxsize=None)
    def uwd(state: int, winner_to_move: bool) -> int:
        g = grundy[state]
        if winner_to_move:
            if g == 0:
                return 0
            win = [c for c in children(state) if grundy[c] == 0]
            if len(win) != 1:
                return 0
            child = win[0]
            opp = children(child)
            if not opp:
                return 1
            return 1 + min(uwd(o, True) for o in opp)
        else:
            ch = children(state)
            if not ch:
                return 0
            return min(uwd(c, True) for c in ch)

    g0 = grundy[0]
    uwd_empty = uwd(0, True) if g0 != 0 else 0
    # scan N positions with |S|<=6 for max uwd (cap the scan)
    max_u = 0
    wit = None
    scanned = 0
    for occ in safe_sets:
        if occ.bit_count() > 6:
            continue
        if grundy[occ] == 0:
            continue
        scanned += 1
        d = uwd(occ, True)
        if d > max_u:
            max_u = d
            wit = occ
    b236 = {
        "g0": g0,
        "uwd_from_empty": uwd_empty,
        "max_uwd_Sle6": max_u,
        "witness": wit,
        "scanned_N": scanned,
    }
    print("b236", b236, flush=True)

    # write partial so far (B237 is slow)
    out = {
        "n": n,
        "n_safe": len(safe_sets),
        "K": board.max_safe_size(),
        "b231": b231,
        "b233": b233,
        "b236": b236,
        "b241": b241,
        "b247": b247,
        "b249": b249,
    }
    json.dump(out, open(OUT, "w"), indent=2, ensure_ascii=False)
    print("WROTE partial", OUT, flush=True)

    # B237 component jump, sample |S|<=3 only (cheap)
    max_jump = 0
    jump_w = None
    for occ in safe_sets:
        if occ.bit_count() > 3:
            continue
        adj0 = residual_graph(board, occ)
        cn = len(comps(adj0))
        for v in legal[occ]:
            nxt = occ | (1 << v)
            cn2 = len(comps(residual_graph(board, nxt)))
            if cn2 - cn > max_jump:
                max_jump = cn2 - cn
                jump_w = (occ, v, cn, cn2)
    b237 = {"max_jump_Sle3": max_jump, "witness": jump_w}
    print("b237", b237, flush=True)
    out["b237"] = b237
    json.dump(out, open(OUT, "w"), indent=2, ensure_ascii=False)
    print("WROTE", OUT)


if __name__ == "__main__":
    main()
